// 自分と相手のMBTIの軸の一致/補完から相性理由の文章を組み立てる
export function pairReason(me: MbtiType, them: MbtiType): string {
  const parts: string[] = [];

  if (me[1] === them[1]) {
    parts.push(
      me[1] === 'N'
        ? '2人とも直感型なので、抽象的な話や将来の話で自然と盛り上がれます'
        : '2人とも現実感覚を大切にするタイプなので、地に足のついた会話で安心できます',
    );
  } else {
    parts.push('ものの見方が異なるため、新鮮な発見がある一方、話が噛み合うまで少し時間がかかるかもしれません');
  }

  if (me[0] !== them[0]) {
    parts.push('外向と内向の組み合わせで、話す側と聞く側のバランスが取りやすい関係です');
  } else if (me[0] === 'E') {
    parts.push('お互い外向的なので、会話が途切れず賑やかな時間になりそうです');
  } else {
    parts.push('お互い内向的なので、静かな場所でじっくり話すのが合っています');
  }

  if (me[3] !== them[3]) {
    parts.push('計画派と柔軟派で、お互いにないリズムを補い合えます');
  }
  if (me[2] === them[2]) {
    parts.push(me[2] === 'F' ? '感情を大切にする者同士、共感し合いやすいのも好材料です' : '論理的に考える者同士、話が早いのも好材料です');
  }

  return parts.join('。') + '。';
}
